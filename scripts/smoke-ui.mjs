import { chromium } from 'playwright';
import { existsSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';

const root = resolve('dist');
if (!existsSync(resolve(root, 'index.html'))) throw new Error('Run the renderer build first.');
await import('./build-preview.mjs');
const browserPath = process.env.FIELDMARK_BROWSER || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
let browser;
try {
 browser = await chromium.launch({ headless: true, ...(browserPath ? { executablePath: browserPath } : {}) });
 const page = await browser.newPage({ viewport: { width: 1450, height: 1040 } });
 const errors = []; page.on('pageerror', error => errors.push(error.message));
 const url = pathToFileURL(resolve('dist/Fieldmark-preview.html')).href;
 await page.goto(url);
 await page.getByRole('heading', { name: /Find what the spec leaves out/ }).waitFor();
 mkdirSync('test-results', { recursive: true });
 await page.screenshot({ path: 'test-results/new-investigation.png', fullPage: true });
 await page.getByRole('button', { name: /See an example investigation/ }).click();
 await page.getByRole('heading', { name: /AXR-1200.*equipment resource package/ }).waitFor();
 assert.equal(await page.locator('.evidence-card').count(), 3);
 await page.getByRole('button', { name: 'Exact model', exact: true }).click();
 assert.equal(await page.locator('.evidence-card').count(), 1);
 await page.getByRole('tab', { name: /Research answer/ }).click();
 assert.match(await page.locator('.answer-text').innerText(), /fictional demonstration/);
 await page.getByRole('tab', { name: /Activity/ }).click();
 assert.match(await page.locator('.activity-panel').innerText(), /No searches or API calls/);
 await page.getByRole('tab', { name: /Evidence/ }).click();
 await page.getByRole('button', { name: 'All sources', exact: true }).click();
 await page.screenshot({ path: 'test-results/sample-investigation.png', fullPage: true });
 await page.reload();
 await page.getByRole('button', { name: /AXR-1200.*equipment resource package/ }).first().waitFor();
 await page.getByRole('button', { name: /New investigation/ }).first().click();
 await page.getByLabel('Manufacturer', { exact: true }).fill('Acme Test');
 await page.getByLabel('Model / product number', { exact: true }).fill('Z-42');
 await page.getByRole('button', { name: 'Save draft', exact: true }).click();
 await page.getByRole('heading', { name: /Acme Test.*Z-42/ }).waitFor();
 assert.match(await page.locator('.request-summary').innerText(), /find|search|discover/i);
 await page.getByRole('button', { name: 'Start research', exact: true }).click();
 await page.getByRole('alert').waitFor();
 assert.match(await page.getByRole('alert').innerText(), /desktop|preview/i);
 await page.getByRole('button', { name: /Settings & connection/ }).click();
 await page.getByRole('heading', { name: /Settings/ }).first().waitFor();
 assert.equal(await page.locator('input[type="password"]').count(), 1);
 await page.screenshot({ path: 'test-results/settings.png', fullPage: true });
 await page.getByRole('button', { name: /Asset vault/ }).first().click();
 assert.match(await page.locator('main').innerText(), /No saved|Your files|No assets|saved files|download/i);
 assert.deepEqual(errors, []);
 console.log('UI smoke passed: initial page, sample, filters, answer, activity, persistence, default draft request, honest live-mode rejection, settings, vault; no browser errors.');
} finally { await browser?.close(); }
